-- 1. Cipta Jadual pksk_licenses
CREATE TABLE IF NOT EXISTS public.pksk_licenses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  license_key VARCHAR(30) UNIQUE NOT NULL,
  status VARCHAR(20) DEFAULT 'ACTIVE',
  tier VARCHAR(30) DEFAULT 'PREMIUM_FULL',
  max_devices INT DEFAULT 1,
  device_id TEXT,
  activated_by_name TEXT,
  activated_by_ic TEXT,
  activated_at TIMESTAMPTZ,
  expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ DEFAULT now()
);

-- 2. Cipta Index untuk carian pantas
CREATE INDEX IF NOT EXISTS idx_pksk_license_key ON public.pksk_licenses (license_key);
CREATE INDEX IF NOT EXISTS idx_pksk_status ON public.pksk_licenses (status);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.pksk_licenses ENABLE ROW LEVEL SECURITY;

-- 4. Polisi RLS: Benarkan Anon memeriksa kunci lesen
DROP POLICY IF EXISTS "Allow public to check license" ON public.pksk_licenses;
CREATE POLICY "Allow public to check license"
ON public.pksk_licenses FOR SELECT
USING (true);

-- 5. Polisi RLS: Benarkan Anon mengaktifkan lesen yang masih ACTIVE
DROP POLICY IF EXISTS "Allow public to activate license" ON public.pksk_licenses;
CREATE POLICY "Allow public to activate license"
ON public.pksk_licenses FOR UPDATE
USING (true)
WITH CHECK (true);

